#!/usr/bin/env node
/**
 * Provisions NATS accounts for the PiHub relay (runs on the relay host).
 *
 *   node relay-provision.mjs add-node <nodeId>     → prints the connector config JSON
 *   node relay-provision.mjs remove-node <nodeId>
 *   node relay-provision.mjs add-desktop           → prints the shared desktop token
 *   node relay-provision.mjs list
 *   node relay-provision.mjs connector-config <nodeId>
 *
 * Source of truth is ACCOUNTS_JSON; the rendered NATS include file is
 * regenerated atomically and the server is reloaded via HUP.
 *
 * Security model: NATS accounts are transport-level isolation only. The real
 * authorization stays end-to-end (PiHub HMAC request signing between desktop
 * and node); a leaked desktop token cannot impersonate a paired device.
 */
import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const RELAY_DIR = process.env.PIHUB_RELAY_DIR || process.cwd();
const ACCOUNTS_JSON = path.join(RELAY_DIR, "accounts.json");
const ACCOUNTS_CONF = path.join(RELAY_DIR, "accounts.conf");
const NATS_CONTAINER = process.env.PIHUB_RELAY_NATS_CONTAINER || "pihub-relay-nats";
const RELAY_URL = "wss://relay.ffuu.eu.org";

function fail(message) {
  console.error(`provision: ${message}`);
  process.exit(1);
}

function loadAccounts() {
  try {
    const data = JSON.parse(fs.readFileSync(ACCOUNTS_JSON, "utf8"));
    if (typeof data !== "object" || data === null) throw new Error("bad shape");
    return { desktop: data.desktop ?? null, nodes: data.nodes ?? {} };
  } catch (error) {
    if (error.code === "ENOENT") return { desktop: null, nodes: {} };
    fail(`无法读取 ${ACCOUNTS_JSON}：${error.message}`);
  }
}

function renderConf(accounts) {
  const users = [];
  if (accounts.desktop) {
    users.push(`    { user: desktop, password: "${accounts.desktop}", permissions: {
      publish:   { allow: ["node.>", "_INBOX.>"] }
      subscribe: { allow: ["_INBOX.>", "node.*.events.>", "node.*.xfer.>"] }
    } }`);
  }
  for (const [nodeId, token] of Object.entries(accounts.nodes)) {
    users.push(`    { user: "node-${nodeId}", password: "${token}", permissions: {
      publish:   { allow: ["_INBOX.>", "node.${nodeId}.events.>", "node.${nodeId}.xfer.>"] }
      subscribe: { allow: ["node.${nodeId}.>"] }
    } }`);
  }
  return `# Generated by relay-provision.mjs — do not edit by hand.
accounts {
  RELAY {
    users: [
${users.join(",\n")}
    ]
  }
}
`;
}

function saveAccounts(accounts) {
  fs.mkdirSync(path.dirname(ACCOUNTS_JSON), { recursive: true });
  const tmp = `${ACCOUNTS_JSON}.tmp`;
  fs.writeFileSync(tmp, `${JSON.stringify(accounts, null, 2)}\n`, { mode: 0o600 });
  fs.renameSync(tmp, ACCOUNTS_JSON);

  const confTmp = `${ACCOUNTS_CONF}.tmp`;
  fs.writeFileSync(confTmp, renderConf(accounts), { mode: 0o644 });
  fs.renameSync(confTmp, ACCOUNTS_CONF);

  try {
    execFileSync("docker", ["kill", "-s", "HUP", NATS_CONTAINER], { stdio: "pipe" });
  } catch {
    console.error("provision: 无法 HUP nats 容器，请手动 docker restart " + NATS_CONTAINER);
  }
}

function newToken() {
  return crypto.randomBytes(32).toString("base64url");
}

function validNodeId(value) {
  return typeof value === "string" && /^[a-z0-9][a-z0-9-]{0,62}$/.test(value);
}

const [command, nodeId] = process.argv.slice(2);
const accounts = loadAccounts();

switch (command) {
  case "add-node": {
    if (!validNodeId(nodeId)) fail("nodeId 必须是 [a-z0-9-]，最长 63 字符");
    if (accounts.nodes[nodeId]) fail(`节点 ${nodeId} 已存在（先 remove-node 再加）`);
    accounts.nodes[nodeId] = newToken();
    saveAccounts(accounts);
    console.log(JSON.stringify({ relayUrl: RELAY_URL, nodeId, user: `node-${nodeId}`, token: accounts.nodes[nodeId] }, null, 2));
    break;
  }
  case "remove-node": {
    if (!accounts.nodes[nodeId]) fail(`节点 ${nodeId} 不存在`);
    delete accounts.nodes[nodeId];
    saveAccounts(accounts);
    console.log(`已移除节点 ${nodeId}`);
    break;
  }
  case "add-desktop": {
    accounts.desktop = newToken();
    saveAccounts(accounts);
    console.log(JSON.stringify({ relayUrl: RELAY_URL, user: "desktop", token: accounts.desktop }, null, 2));
    break;
  }
  case "connector-config": {
    const token = accounts.nodes[nodeId];
    if (!token) fail(`节点 ${nodeId} 不存在`);
    console.log(JSON.stringify({ relayUrl: RELAY_URL, nodeId, user: `node-${nodeId}`, token }, null, 2));
    break;
  }
  case "list": {
    // Also re-renders accounts.conf: doubles as a repair/reload command.
    saveAccounts(accounts);
    console.log(JSON.stringify({
      desktop: accounts.desktop ? "已配置" : "未配置",
      nodes: Object.keys(accounts.nodes).sort(),
    }, null, 2));
    break;
  }
  default:
    console.error("用法：relay-provision.mjs <add-node|remove-node|add-desktop|connector-config|list> [nodeId]");
    process.exit(1);
}
